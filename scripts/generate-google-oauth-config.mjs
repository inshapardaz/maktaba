#!/usr/bin/env node
// Generates the two gitignored source files googleDriveAuth.ts and GoogleDriveStorageProvider.cs's
// GoogleOAuthConfig import their Google OAuth CLIENT_ID/CLIENT_SECRET from, so the real values
// never need to be committed to git. GitHub's push protection rightly blocks a literal client
// secret appearing in a commit - even one from an OAuth client type Google's own docs say doesn't
// need to stay confidential in principle (see CLAUDE.md's "Cloud storage" section), since it still
// shouldn't sit in git history forever. Run before any build (see the root package.json's `pre*`
// hooks) so it never goes stale relative to whatever MAKTABA_GOOGLE_CLIENT_ID/_SECRET currently is.
//
// Sourced from environment variables - set locally for dev, or as GitHub Actions repository
// secrets for CI packaging (see README.md's "Google Drive OAuth setup").
//
// Safe to run with neither variable set (local dev before Google Drive is needed at all, or a CI
// job that hasn't been given the secrets yet) - writes empty placeholders and warns, rather than
// failing the whole build over what's an optional feature.

import { writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";

const clientId = process.env.MAKTABA_GOOGLE_CLIENT_ID ?? "";
const clientSecret = process.env.MAKTABA_GOOGLE_CLIENT_SECRET ?? "";

if (!clientId || !clientSecret) {
  console.warn(
    "[generate-google-oauth-config] MAKTABA_GOOGLE_CLIENT_ID / MAKTABA_GOOGLE_CLIENT_SECRET are not " +
      "both set - Google Drive sign-in will fail until they are. See README.md's 'Google Drive OAuth setup'.",
  );
}

const generatedNotice =
  "// AUTO-GENERATED by scripts/generate-google-oauth-config.mjs - do not edit by hand, do not commit.\n" +
  '// See README.md\'s "Google Drive OAuth setup" for how this file is produced.\n';

const files = [
  {
    path: "apps/desktop/src/googleOAuthConfig.generated.ts",
    content:
      generatedNotice +
      `export const GOOGLE_CLIENT_ID = ${JSON.stringify(clientId)};\n` +
      `export const GOOGLE_CLIENT_SECRET = ${JSON.stringify(clientSecret)};\n`,
  },
  {
    path: "backend/Maktaba.Cloud/GoogleOAuthConfig.Generated.cs",
    content:
      generatedNotice +
      "namespace Maktaba.Cloud;\n\n" +
      "internal static class GoogleOAuthConfig\n{\n" +
      `    public const string ClientId = ${JSON.stringify(clientId)};\n` +
      `    public const string ClientSecret = ${JSON.stringify(clientSecret)};\n` +
      "}\n",
  },
];

for (const { path, content } of files) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content, "utf8");
  console.log(`[generate-google-oauth-config] wrote ${path}`);
}
